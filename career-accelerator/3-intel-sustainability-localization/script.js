function getSupportedLanguage(languageCode) {
    const shortCode = languageCode.slice(0, 2).toLowerCase();

    if (translations[shortCode]) {
        return shortCode;
    }

    return "en";
}

function updateText(language) {
    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.getAttribute("data-i18n");

        if (translations[language][key]) {
            element.textContent = translations[language][key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        const key = element.getAttribute("data-i18n-placeholder");

        if (translations[language][key]) {
            element.setAttribute("placeholder", translations[language][key]);
        }
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
        const key = element.getAttribute("data-i18n-aria-label");

        if (translations[language][key]) {
            element.setAttribute("aria-label", translations[language][key]);
        }
    });
}

function updateDirection(language) {
    const rtlLanguages = ["ar", "he", "fa", "ur"];

    document.documentElement.lang = language;

    if (rtlLanguages.includes(language)) {
        document.documentElement.dir = "rtl";
    } else {
        document.documentElement.dir = "ltr";
    }
}

function applyBrowserLanguage() {
    const browserLanguage = navigator.language || navigator.userLanguage || "en";
    const language = getSupportedLanguage(browserLanguage);

    updateDirection(language);
    updateText(language);
}

document.addEventListener("DOMContentLoaded", applyBrowserLanguage);